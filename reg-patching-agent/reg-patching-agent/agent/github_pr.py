"""Step 4: branch, commit, test, and open a DRAFT PR with an audit trail."""
import os, subprocess, requests

API = "https://api.github.com"


def sh(*args):
    return subprocess.run(args, capture_output=True, text=True, check=True)


def _h():
    return {"Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}",
            "Accept": "application/vnd.github+json"}


def branch_exists(repo, branch):
    return requests.get(f"{API}/repos/{repo}/branches/{branch}", headers=_h(), timeout=30).status_code == 200


def run_tests(cmd):
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    return r.returncode == 0, (r.stdout + r.stderr)[-3000:]


def open_pr(repo, base, branch, title, body, cfg, changed_files, doc_id):
    sh("git", "checkout", "-b", branch)
    sh("git", "add", *changed_files)
    sh("git", "commit", "-m", f"{title}\n\nRegulatory-Doc: {doc_id}\nGenerated-By: regulatory-patching-agent")
    sh("git", "push", "origin", branch)
    r = requests.post(f"{API}/repos/{repo}/pulls", headers=_h(), timeout=30, json={
        "title": title, "head": branch, "base": base, "body": body, "draft": True})
    r.raise_for_status()
    pr = r.json()
    num = pr["number"]
    requests.post(f"{API}/repos/{repo}/issues/{num}/labels", headers=_h(), timeout=30,
                  json={"labels": cfg["labels"]})
    if cfg.get("reviewers_team"):
        requests.post(f"{API}/repos/{repo}/pulls/{num}/requested_reviewers", headers=_h(), timeout=30,
                      json={"team_reviewers": [cfg["reviewers_team"]]})
    sh("git", "checkout", base)
    return pr["html_url"]


def render_body(doc, analysis, results, tests_ok, test_log):
    rows = "\n".join(f"| `{p}` | {', '.join(r['ids'])} | {r['rationale']} |" for p, r in results.items())
    obs = "\n".join(f"- **{o['id']}** ({o.get('citation') or 'n/a'}): {o['requirement']}"
                    for o in analysis["obligations"])
    qs = [q for r in results.values() for q in r.get("open_questions", [])]
    qtxt = "\n".join(f"- [ ] {q}" for q in qs) or "_None flagged_"
    status = "✅ passed" if tests_ok else "❌ FAILED — do not merge"
    return f"""## Regulatory patch (AI-generated draft)
**Source:** [{doc['title']}]({doc['url']}) — {doc['source']}
**Effective date:** {analysis.get('effective_date') or 'unspecified'}
**Model confidence:** {analysis.get('confidence')}

### Summary
{analysis['summary']}

### Obligations addressed
{obs}

### Changes
| File | Obligations | Rationale |
|---|---|---|
{rows}

### Open questions for Compliance
{qtxt}

### Tests: {status}
<details><summary>Log</summary>

```
{test_log}
```
</details>

### Required before merge
- [ ] Compliance officer sign-off
- [ ] Legal confirms interpretation of the cited rule
- [ ] Model-risk / change-management ticket linked

> This PR was generated by an AI agent. It is a **draft** and must never be auto-merged.
"""
